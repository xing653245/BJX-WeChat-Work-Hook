const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { saveInjectSettings } = require('../services/injectSettings')
test('保存仅修改 host，忽略回调、加密、端口参数并支持回滚', t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'host-config-'))
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }))
  const host = path.join(dir, 'WXWork.exe')
  fs.writeFileSync(host, '')
  const original = { host: 'old.exe', port: '8989', enabled: true, retries: 2, RSA_PublicKey: 'unchanged', Message_Encryption: true, custom: { keep: true } }
  const file = path.join(dir, 'settings.json')
  fs.writeFileSync(file, JSON.stringify(original))
  const undo = saveInjectSettings(dir, { host, port: 1234, enabled: false, retries: 99, encrypt: false })
  assert.deepEqual(JSON.parse(fs.readFileSync(file)), { ...original, host })
  assert.throws(() => saveInjectSettings(dir, { host: 'missing.exe' }), /不存在/)
  assert.deepEqual(JSON.parse(fs.readFileSync(file)), { ...original, host })
  undo(); undo()
  assert.equal(fs.readFileSync(file, 'utf8'), JSON.stringify(original))
})
