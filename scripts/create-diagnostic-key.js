/** 仅开发端执行一次；私钥输出目录必须在项目之外。 */
const crypto = require('crypto')
const fs = require('fs')
const path = require('path')
const { keyId } = require('../electron/commons/reportEncryption.cjs')
const output = process.argv[2]
if (!output) throw new Error('请指定项目外的私钥目录')
const root = path.resolve(__dirname, '..')
const directory = path.resolve(output)
const relative = path.relative(root, directory)
if (!relative.startsWith('..') && !path.isAbsolute(relative)) throw new Error('私钥不能保存在项目内')
const configPath = path.join(root, 'electron/configs/diagnosticPublicKey.json')
if (fs.existsSync(configPath)) throw new Error('公钥已配置，禁止自动覆盖或重新生成')
fs.mkdirSync(directory, { recursive: true })
const pair = crypto.generateKeyPairSync('rsa', { modulusLength: 3072 })
const privatePath = path.join(directory, 'diagnostic-private.pem')
fs.writeFileSync(privatePath, pair.privateKey.export({ type: 'pkcs8', format: 'pem' }), { flag: 'wx', mode: 0o600 })
fs.writeFileSync(configPath, JSON.stringify({ keyId: keyId(pair.publicKey), publicKey: pair.publicKey.export({ type: 'spki', format: 'der' }).toString('base64') }, null, 2) + '\n', { flag: 'wx' })
console.log('私钥已保存（请备份，不随程序分发）：' + privatePath)
